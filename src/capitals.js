export function capitalAnswerGroups(capitals) {
  return capitals.map(name => [...new Set([
    name, ...capitalNames(name, 'de'), ...capitalNames(name, 'cs'), ...(CAPITAL_ALIASES[name] || []),
  ])]);
}
